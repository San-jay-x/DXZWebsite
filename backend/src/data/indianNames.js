/**
 * Get all names in a flat array for database seeding
 */
const getAllNamesFlat = () => {
  const allNames = [];
  
  // Add male names
  maleNames.forEach(name => {
    allNames.push({
      firstName: name.firstName,
      surname: name.surname,
      gender: 'male'
    });
  });
  
  // Add female names
  femaleNames.forEach(name => {
    allNames.push({
      firstName: name.firstName,
      surname: name.surname,
      gender: 'female'
    });
  });
  
  return allNames;
};

/**
 * Validate the dataset for duplicates and completeness
 */
const validateDataset = () => {
  const maleFullNames = new Set();
  const femaleFullNames = new Set();
  const maleFirstNames = new Set();
  const femaleFirstNames = new Set();
  const maleSurnames = new Set();
  const femaleSurnames = new Set();
  
  // Check male names
  maleNames.forEach(name => {
    const fullName = `${name.firstName} ${name.surname}`;
    if (maleFullNames.has(fullName)) {
      console.warn(`Duplicate male name found: ${fullName}`);
    }
    maleFullNames.add(fullName);
    maleFirstNames.add(name.firstName);
    maleSurnames.add(name.surname);
  });
  
  // Check female names
  femaleNames.forEach(name => {
    const fullName = `${name.firstName} ${name.surname}`;
    if (femaleFullNames.has(fullName)) {
      console.warn(`Duplicate female name found: ${fullName}`);
    }
    femaleFullNames.add(fullName);
    femaleFirstNames.add(name.firstName);
    femaleSurnames.add(name.surname);
  });
  
  return {
    maleCount: maleNames.length,
    femaleCount: femaleNames.length,
    totalCount: maleNames.length + femaleNames.length,
    maleUniqueFirstNames: maleFirstNames.size,
    femaleUniqueFirstNames: femaleFirstNames.size,
    maleUniqueSurnames: maleSurnames.size,
    femaleUniqueSurnames: femaleSurnames.size,
    isValid: maleNames.length === 500 && femaleNames.length === 500
  };
};

